function check(
  id: string,
  label: string,
  type: string,
  host: string,
  value: string,
  status: 'ready' | 'fail' | 'waiting',
  code: ErrorCode | null,
): MailDomain['checks'][number] {
  return { id, label, type, host, value, status, code };
}

